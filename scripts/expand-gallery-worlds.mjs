function entityRecord(e) {
  return {
    id: e.id,
    type: e.type,
    label: e.label,
    promptPoint: e.promptPoint,
    position: [0, 0, 0],
    scale: [1, 1, 1],
    depth: e.type === 'landscape' || e.type === 'architecture' ? 2 : 1,
    importance: e.importance,
    interactive: true,
    confidence: 0.88,
    evidence: 'observed',
  }
}

function planeSize(aspect, base = 16) {
  if (aspect >= 1) return { planeWidth: base, planeHeight: Math.round((base / aspect) * 1000) / 1000 }
  return { planeWidth: Math.round(base * aspect * 1000) / 1000, planeHeight: base }
}

async function commonsInfo(title) {
  const url =
    'https://commons.wikimedia.org/w/api.php?action=query&format=json&prop=imageinfo&iiprop=url|size|extmetadata&iiurlwidth=1600&titles=' +
    encodeURIComponent(title)
  const res = await fetch(url, { headers: { 'User-Agent': UA } })
  if (!res.ok) throw new Error(`Commons API ${res.status} for ${title}`)
  const json = await res.json()
  const page = Object.values(json.query.pages)[0]
  if (page.missing || !page.imageinfo?.[0]) throw new Error(`Missing Commons file: ${title}`)
  return page.imageinfo[0]
}

async function download(url, dest) {
  const res = await fetch(url, { headers: { 'User-Agent': UA } })
  if (!res.ok) throw new Error(`Download failed ${res.status}: ${url}`)
  const buf = Buffer.from(await res.arrayBuffer())
  fs.writeFileSync(dest, buf)
  return buf.length
}

async function pack(work) {
  const dir = path.join(OUT, work.id)
  if (fs.existsSync(path.join(dir, 'manifest.json'))) {
    console.log(`→ ${work.id} … skip (exists)`)
    return {
      id: work.id,
      worldId: work.id,
      title: work.title,
      artist: work.artist,
      year: work.year,
      src: `/data/paintings/${work.id}/thumb.webp`,
      alt: `${work.artist}, ${work.title}`,
      widthClass: work.widthClass,
      skipped: true,
    }
  }
  process.stdout.write(`→ ${work.id} … `)
  fs.mkdirSync(dir, { recursive: true })
  const info = await commonsInfo(work.commonsTitle)
  const thumb = info.thumburl || info.url
  const bytes = await download(thumb, path.join(dir, 'painting.jpg'))
  const aspect = (info.thumbwidth || info.width) / (info.thumbheight || info.height)
  const { planeWidth, planeHeight } = planeSize(aspect)
  const museumSource = work.museumUrl

  const manifest = {
    schemaVersion: 1,
    paintingId: work.id,
    pipelineVersion: '0.1.0',
    sceneAnalysisVersion: 'manual-curiosities-v3',
    segmentationVersion: 'none',
    depthVersion: 'none',
    painting: {
      title: work.title,
      artist: work.artist,
      date: work.year,
      medium: work.medium,
      source: work.museum,
    },
    composition: {
      aspectRatio: Math.round(aspect * 1000) / 1000,
      horizon: work.horizon,
      vanishingPoint: [0.5, work.horizon],
      cameraFov: work.fov,
      planeWidth,
      planeHeight,
    },
    layers: [
      {
        id: 'hero-painting',
        label: 'Painting plane',
        depthBand: 0,
        texture: 'painting.jpg',
        z: 0,
        parallax: 1,
        opacity: 1,
        hero: true,
      },
    ],
    entities: work.entities.map(entityRecord),
    architecture: [],
    lighting: work.lighting,
    palette: work.palette,
  }

  const facts = {
    facts: work.facts.map((f) => ({
      ...f,
      sources: [museumSource],
    })),
  }

  const sources = {
    paintingId: work.id,
    image: {
      file: 'painting.jpg',
      sourceUrl: info.descriptionurl,
      retrievalUrl: thumb,
      license: 'Public domain',
      credit: info.extmetadata?.Artist?.value?.replace(/<[^>]+>/g, '') || work.artist,
      retrievedAt: new Date().toISOString().slice(0, 10),
      licenseShortName: 'Public domain',
      commonsLicense: 'pd',
      copyrighted: false,
      commonsTitle: work.commonsTitle,
      commonsUrl: info.descriptionurl,
      rights: {
        status: 'public_domain',
        verifiedVia: 'Wikimedia Commons',
        verifiedAt: new Date().toISOString().slice(0, 10),
        artistDeathYear: work.deathYear,
        workPublicDomainReason: `${work.artist} died in ${work.deathYear}; the painting is in the public domain worldwide.`,
        reproductionNote: 'Wikimedia Commons reproduction used for the curated 2D world pack.',
      },
    },
    references: [{ id: `${work.id}-museum`, title: work.title, publisher: work.museum, url: museumSource }],
  }

  fs.writeFileSync(path.join(dir, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n')
  fs.writeFileSync(path.join(dir, 'facts.json'), JSON.stringify(facts, null, 2) + '\n')
  fs.writeFileSync(path.join(dir, 'sources.json'), JSON.stringify(sources, null, 2) + '\n')
  console.log(`ok (${(bytes / 1024).toFixed(0)} KB, ${manifest.entities.length} curiosities)`)
  return {
    id: work.id,
    worldId: work.id,
    title: work.title,
    artist: work.artist,
    year: work.year,
    src: `/data/paintings/${work.id}/thumb.webp`,
    alt: `${work.artist}, ${work.title}`,
    widthClass: work.widthClass,
  }
}

async function main() {
  fs.mkdirSync(OUT, { recursive: true })
  const gallery = []
  for (const work of WORKS) {
    try {
      gallery.push(await pack(work))
    } catch (err) {
      console.log(`FAIL`)
      console.error(`  ${work.id}: ${err.message}`)
    }
  }
  fs.writeFileSync(path.join(OUT, '_new-gallery-entries.json'), JSON.stringify(gallery, null, 2) + '\n')
  console.log(`\nWrote/kept ${gallery.length} entries → _new-gallery-entries.json`)
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})
