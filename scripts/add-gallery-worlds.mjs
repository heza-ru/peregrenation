function entityRecord(e) {
  return {
    id: e.id,
    type: e.type,
    label: e.label,
    promptPoint: e.promptPoint,
    position: [0, 0, 0],
    scale: [1, 1, 1],
    depth: e.type === 'landscape' || e.type === 'architecture' ? 2 : 1,
    importance: e.importance,
    interactive: true,
    confidence: 0.88,
    evidence: 'observed',
  }
}

function planeSize(aspect, base = 16) {
  if (aspect >= 1) return { planeWidth: base, planeHeight: Math.round((base / aspect) * 1000) / 1000 }
  return { planeWidth: Math.round(base * aspect * 1000) / 1000, planeHeight: base }
}

async function commonsInfo(title) {
  const url =
    'https://commons.wikimedia.org/w/api.php?action=query&format=json&prop=imageinfo&iiprop=url|size|extmetadata&iiurlwidth=1600&titles=' +
    encodeURIComponent(title)
  const res = await fetch(url, { headers: { 'User-Agent': UA } })
  if (!res.ok) throw new Error(`Commons API ${res.status} for ${title}`)
  const json = await res.json()
  const page = Object.values(json.query.pages)[0]
  if (page.missing || !page.imageinfo?.[0]) throw new Error(`Missing Commons file: ${title}`)
  return page.imageinfo[0]
}

async function download(url, dest) {
  const res = await fetch(url, { headers: { 'User-Agent': UA } })
  if (!res.ok) throw new Error(`Download failed ${res.status}: ${url}`)
  const buf = Buffer.from(await res.arrayBuffer())
  fs.writeFileSync(dest, buf)
  return buf.length
}

